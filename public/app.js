// ============================================================================
function attachSwipeToDismiss() {
  document.querySelectorAll("dialog.booking-dialog").forEach((dialog) => {
    const card = dialog.querySelector(".dialog-card");
    if (!card) return;
    let startY = 0;
    let currentY = 0;
    let tracking = false;

    card.addEventListener(
      "touchstart",
      (e) => {
        if (card.scrollTop > 4) return;
        const touch = e.touches[0];
        startY = touch.clientY;
        currentY = startY;
        tracking = true;
      },
      { passive: true }
    );

    card.addEventListener(
      "touchmove",
      (e) => {
        if (!tracking) return;
        currentY = e.touches[0].clientY;
        const deltaY = currentY - startY;
        if (deltaY > 12) {
          card.style.transform = `translateY(${Math.min(deltaY, 220)}px)`;
        }
      },
      { passive: true }
    );

    card.addEventListener(
      "touchend",
      () => {
        if (!tracking) return;
        tracking = false;
        const deltaY = currentY - startY;
        card.style.transform = "";
        if (deltaY > 95) {
          closeDialog(dialog);
        }
      },
      { passive: true }
    );
  });

  const drawer = document.getElementById("menu-drawer");
  if (drawer) {
    let startX = 0;
    let currentX = 0;
    drawer.addEventListener(
      "touchstart",
      (e) => {
        startX = e.touches[0].clientX;
        currentX = startX;
      },
      { passive: true }
    );
    drawer.addEventListener(
      "touchmove",
      (e) => {
        currentX = e.touches[0].clientX;
      },
      { passive: true }
    );
    drawer.addEventListener(
      "touchend",
      () => {
        if (currentX - startX > 70) {
          closeNavigationDrawer();
        }
      },
      { passive: true }
    );
  }
}

function openNavigationDrawer() {
  const drawer = document.getElementById("menu-drawer");
  const backdrop = document.getElementById("menu-drawer-backdrop");
  const toggleBtn = document.getElementById("menu-toggle-btn");
  if (!drawer) return;
  drawer.classList.add("is-open");
  drawer.setAttribute("aria-hidden", "false");
  if (backdrop) {
    backdrop.hidden = false;
    backdrop.classList.add("is-open");
  }
  if (toggleBtn) {
    toggleBtn.classList.add("is-active");
    toggleBtn.setAttribute("aria-expanded", "true");
  }
  lockBodyScroll();
}

function closeNavigationDrawer() {
  const drawer = document.getElementById("menu-drawer");
  const backdrop = document.getElementById("menu-drawer-backdrop");
  const toggleBtn = document.getElementById("menu-toggle-btn");
  if (!drawer) return;
  drawer.classList.remove("is-open");
  drawer.setAttribute("aria-hidden", "true");
  if (backdrop) {
    backdrop.classList.remove("is-open");
    backdrop.hidden = true;
  }
  if (toggleBtn) {
    toggleBtn.classList.remove("is-active");
    toggleBtn.setAttribute("aria-expanded", "false");
  }
  if (!hasAnyOpenDialog()) {
    unlockBodyScroll();
  }
}

